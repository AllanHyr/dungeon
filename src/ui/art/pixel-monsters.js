/** Deux yeux symétriques (autour de x = 16) : `at` = [x de l'œil gauche, y], `w` = largeur ; le pixel intérieur brille. */
function eyes([x, y], color, core = '#ffffff', w = 2) {
  const right = 31 - x;
  const left = Array.from({ length: w }, (_, i) => [x + i, y]);
  const rightPx = Array.from({ length: w }, (_, i) => [right - i, y]);
  return [[color, [...left, ...rightPx]], [core, [[x + w - 1, y], [right - w + 1, y]]]];
}
const mirror = (list) => [...list, ...list.map(([x, y]) => [31 - x, y])];

