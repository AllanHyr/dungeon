const bodyCache = new Map();
/** Le dessin d'une icône pixel (le contenu du <svg>, en viewBox 0 0 16 16), ou null si elle n'existe pas. */
export function pixelIconBody(name) {
  const def = PIXEL_ICONS[name];
  if (!def) return null;
  if (!bodyCache.has(name)) bodyCache.set(name, iconBody(def));
  return bodyCache.get(name);
}

/**
 * L'icône d'un OBJET : son emplacement, affiné d'après son nom (une hache a une icône de hache, un grimoire de livre...).
 * Un objet peut aussi imposer la sienne : champ "icon" dans data/items.json.
 */
export function itemIconName(def) {
  if (!def) return 'unknown';
  if (def.icon) return def.icon;
  const n = (def.name || '').toLowerCase();
  const has = (...words) => words.some((w) => n.includes(w));
  if (def.slot === 'weapon') {
    if (has('dague', 'surin', 'croc')) return 'dagger';
    if (has('hache')) return 'axe';
    if (has('bâton')) return 'staff';
    if (has('masse', 'massue', 'gourdin')) return has('gourdin', 'massue') ? 'club' : 'mace';
    if (has('marteau')) return 'hammer';
    if (has('faux')) return 'scythe';
    if (has('hallebarde', 'fauchard', 'pic de guerre', 'lance')) return 'polearm';
    if (has('sceptre')) return 'sceptre';
    if (has('pioche')) return 'pickaxe';
    if (has('défense')) return 'tusk';
    return 'sword';
  }
  if (def.slot === 'offhand') {
    if (has('grimoire', 'livre')) return 'book';
    if (has('orbe')) return 'orb';
    if (has('rondache', 'targe')) return 'buckler';
    return 'offhand';
  }
  if (def.slot === 'relic') {
    if (has('fiole')) return 'vial';
    if (has('œil', 'oeil')) return 'eye';
    if (has('larme')) return 'drop';
    if (has('sablier')) return 'hourglass';
    if (has('cœur', 'coeur')) return 'heart';
    if (has('orbe')) return 'orb';
    if (has('calice')) return 'chalice';
    return 'relic';
  }
  if (def.slot === 'consumable') return 'potion';
  return def.slot;
}
