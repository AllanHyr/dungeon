// ============================================================
//  pixel-icons.js — Les icônes du jeu en pixel art (16 × 16), direction « Table pixel »
// ============================================================
// Chaque icône est faite de quelques formes (comme les portraits, voir art/pixel.js), sur une grille de 16 × 16.
// Le moteur ombre chaque forme (liseré clair en haut à gauche, bord sombre en bas à droite) puis pose un contour sombre.
// Les icônes gardent la COULEUR DU TEXTE autour d'elles (currentColor) : une icône d'objet prend la couleur de sa rareté,
// une icône de sort celle de son rôle... Seuls quelques pixels sont fixes (blanc « w », noir « k »).
//
// Les caractères de la grille : '.' vide · '#' couleur · '+' couleur éclaircie · '-' couleur assombrie · 'o' contour
//                               'w' blanc crème · 'k' noir
// Une forme : { e: [cx, cy, rx, ry] } · { r: [x, y, w, h] } · { p: [[x, y], ...] } · { l: [[x, y], ...], w }
//   t: un caractère fixe (sinon : ombrage automatique) · cut: true efface · clip: [x0, y0, x1, y1]
//   g: un groupe (les formes d'un même groupe s'ombrent comme une seule)
// Les détails : px = [[caractère, [[x, y], ...]], ...]

import { inPoly, linePixels } from './art/pixel.js';

const N = 16;

function pixelsOf(sh) {
  const out = [];
  const clip = sh.clip || [-9, -9, 99, 99];
  const ok = (x, y) => x >= 0 && y >= 0 && x < N && y < N && x >= clip[0] && y >= clip[1] && x <= clip[2] && y <= clip[3];
  if (sh.l) return linePixels(sh.l, sh.w || 1).filter(([x, y]) => ok(x, y));
  let inside;
  if (sh.e) { const [cx, cy, rx, ry] = sh.e; inside = (x, y) => ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1; }
  else if (sh.r) { const [x0, y0, w, h] = sh.r; inside = (x, y) => x >= x0 && x < x0 + w && y >= y0 && y < y0 + h; }
  else inside = (x, y) => inPoly(x, y, sh.p);
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) if (ok(x, y) && inside(x + 0.5, y + 0.5)) out.push([x, y]);
  return out;
}

/** La grille de caractères d'une icône. */
export function iconGrid(def) {
  const g = Array.from({ length: N }, () => Array(N).fill('.'));
  // les formes d'un même groupe (g) s'ombrent ensemble, comme une seule forme (le cœur = deux ronds et un triangle)
  const groups = new Map();
  for (const sh of def.s || []) if (sh.g && !sh.cut) {
    if (!groups.has(sh.g)) groups.set(sh.g, new Set());
    for (const [x, y] of pixelsOf(sh)) groups.get(sh.g).add(y * N + x);
  }
  for (const sh of def.s || []) {
    const pts = pixelsOf(sh);
    if (sh.cut) { for (const [x, y] of pts) g[y][x] = '.'; continue; }
    const set = sh.g ? groups.get(sh.g) : new Set(pts.map(([x, y]) => y * N + x));
    const has = (x, y) => set.has(y * N + x);
    for (const [x, y] of pts) {
      let c = sh.t || '#';
      if (!sh.t) {
        const br = !has(x + 1, y) || !has(x, y + 1);
        const tl = !has(x - 1, y) || !has(x, y - 1);
        c = br ? '-' : tl ? '+' : '#';
      }
      g[y][x] = c;
    }
  }
  // le contour
  const out = g.map((row) => row.slice());
  if (def.outline !== false) {
    for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
      if (g[y][x] !== '.') continue;
      if ([[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => (g[y + dy]?.[x + dx] ?? '.') !== '.')) out[y][x] = 'o';
    }
  }
  for (const [c, list] of def.px || []) for (const [x, y] of list) if (x >= 0 && y >= 0 && x < N && y < N) out[y][x] = c;
  return out;
}

const LAYERS = [
  ['#+-o', 'fill="currentColor"'],
  ['+', 'fill="#fff" fill-opacity=".45"'],
  ['-', 'fill="#000" fill-opacity=".28"'],
  ['o', 'fill="#000" fill-opacity=".62"'],
  ['w', 'fill="#fff6e0"'],
  ['k', 'fill="#140a06"']
];
/** Le corps SVG (sans la balise <svg>) d'une icône : quelques chemins, un par calque. */
export function iconBody(def) {
  const g = iconGrid(def);
  return LAYERS.map(([chars, attrs]) => {
    let d = '';
    for (let y = 0; y < N; y++) {
      let x = 0;
      while (x < N) {
        if (!chars.includes(g[y][x])) { x++; continue; }
        let w = 1;
        while (x + w < N && chars.includes(g[y][x + w])) w++;
        d += `M${x} ${y}h${w}v1h-${w}z`;
        x += w;
      }
    }
    return d ? `<path ${attrs} d="${d}"/>` : '';
  }).join('');
}

